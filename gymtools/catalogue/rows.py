def J(joint, needs=1, note=None):
    d = {"joint": joint, "needs": needs}
    if note:
        d["note"] = note
    return d


def R(key, name, kind, **kw):
    d = {"key": key, "name": name, "kind": kind}
    d.update(kw)
    return d


